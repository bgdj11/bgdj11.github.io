import { readFile, writeFile, mkdir } from 'node:fs/promises'

// One restrained palette, with the same contrast steps for every chapter.
// Run `node scripts/generate-section-palettes.mjs` after changing these colors.
const palettes = {
  home: '#a794c8',
  education: '#82aecf',
  experience: '#c7aa73',
  projects: '#8fbe92',
  'beyond-code': '#cd8f91',
  contact: '#7abbb2',
}
const root = new URL('../', import.meta.url)
const mix = (a, b, amount) => '#' + [1, 3, 5].map(i => Math.round(
  parseInt(a.slice(i, i + 2), 16) * (1 - amount) + parseInt(b.slice(i, i + 2), 16) * amount,
).toString(16).padStart(2, '0')).join('')
const templates = {
  panel: 'celadon-panel.svg', media: 'gold-pixel.svg',
  selection: 'selection-corners.svg', card: 'card-selection.svg',
}
const sources = await Promise.all(Object.entries(templates).map(async ([kind, file]) =>
  [kind, await readFile(new URL(`public/frames/${file}`, root), 'utf8')],
))
await mkdir(new URL('public/frames/chapters/', root), { recursive: true })
let css = '/* Generated by scripts/generate-section-palettes.mjs. */\n'
for (const [id, accent] of Object.entries(palettes)) {
  const shade = mix(accent, '#11121b', .48)
  const light = mix(accent, '#fff2df', .55)
  // Retain the pixel geometry and the original bevel lightness hierarchy.
  const recolor = color => {
    const rgb = [1, 3, 5].map(i => parseInt(color.slice(i, i + 2), 16))
    const value = .2126 * rgb[0] + .7152 * rgb[1] + .0722 * rgb[2]
    const base = .2126 * 143 + .7152 * 190 + .0722 * 146
    return value < 22 ? color : value < base
      ? mix(accent, '#07090d', 1 - value / base)
      : mix(accent, '#fff2df', Math.min(.82, (value - base) / (248 - base)))
  }
  for (const [kind, svg] of sources) {
    await writeFile(new URL(`public/frames/chapters/${id}-${kind}.svg`, root), svg.replace(/#[\da-f]{6}/gi, recolor))
  }
  css += `\n[data-accent='${id}'] {
  --color-accent: ${accent};
  --color-secondary: ${light};
  --panel-border: ${shade};
  --panel-rule: ${mix(accent, '#0d1110', .8)};
  --accent-hover: ${light};
  --control-border: ${shade};
  --control-edge: ${mix(accent, '#07090d', .7)};
  --accent-soft: ${mix(accent, '#0d1110', .88)};
  --retro-panel-frame: url('/frames/chapters/${id}-panel.svg');
  --retro-frame: url('/frames/chapters/${id}-media.svg');
  --selection-frame: url('/frames/chapters/${id}-selection.svg');
  --card-selection-frame: url('/frames/chapters/${id}-card.svg');
}\n`
}
await writeFile(new URL('src/styles/section-palettes.css', root), css)
